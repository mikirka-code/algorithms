# Восстановление пути по словарю "откуда пришли"
def build_path(parents, end):
    path = []
    station = end

    # Идём от конечной станции назад к начальной
    while station is not None:
        path.append(station)
        station = parents[station]

    # Разворачиваем, чтобы путь шёл от начала к концу
    path.reverse()
    return path


# Поиск в ширину (BFS) — находит путь с наименьшим числом перегонов
def bfs(graph, start, end):
    queue = deque([start])      # очередь станций, которые нужно проверить
    parents = {start: None}     # откуда пришли в каждую станцию (заодно — посещённые)

    while queue:
        # Берём станцию из начала очереди
        station = queue.popleft()

        # Дошли до нужной станции — восстанавливаем путь
        if station == end:
            return build_path(parents, end)

        # Добавляем в конец очереди всех ещё не посещённых соседей
        for neighbor in graph[station]:
            if neighbor not in parents:
                parents[neighbor] = station
                queue.append(neighbor)

    # Очередь закончилась, а станцию не нашли — пути нет
    return None


# Поиск в глубину (DFS) — идёт как можно дальше по одной ветке,
# путь находит, но не обязательно самый короткий
def dfs(graph, start, end):
    stack = [start]             # стек станций, которые нужно проверить
    parents = {start: None}     # откуда пришли в каждую станцию
    visited = set()             # уже обработанные станции

    while stack:
        # Берём станцию с вершины стека (последнюю добавленную)
        station = stack.pop()

        if station in visited:
            continue
        visited.add(station)

        # Дошли до нужной станции — восстанавливаем путь
        if station == end:
            return build_path(parents, end)

        # Кладём соседей в стек в обратном порядке,
        # чтобы первым проверялся первый сосед из списка
        for neighbor in reversed(graph[station]):
            if neighbor not in visited:
                parents[neighbor] = station
                stack.append(neighbor)

    # Стек опустел — пути нет
    return None


# Поиск станции по введённому названию без учёта регистра
def find_station(graph, name):
    for station in graph:
        if station.lower() == name.strip().lower():
            return station
    return None


# Вывод пути в виде "Станция->Станция->Станция"
def print_path(title, path):
    if path is None:
        print(title, "пути нет")
    else:
        print(title, "->".join(path))


